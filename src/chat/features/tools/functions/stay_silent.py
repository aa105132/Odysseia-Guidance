# -*- coding: utf-8 -*-

"""
静默工具：让 AI 主动选择不回复
"""


async def stay_silent(reason: str = "", **kwargs) -> dict:
    """
    主动选择不回复当前消息。

    当你判断没有必要回复时，调用此工具即可跳过回复。
    调用后你不会发送任何消息，对话就此静默结束。

    [使用指南]
    **核心判断原则**：问自己"如果我是群里的真人，看到这条消息会不会特意回复？"
    如果答案是不会，就大胆用这个工具。不必每条消息都接话，安静也是一种自然。
    即使被 @、被回复，也不代表你必须回复——先判断内容本身值不值得接话。

    **适用场景（应该沉默）**：
    - 群聊中别人在聊天，话题跟你无关，没有人在叫你
    - 其他 bot 的自动消息（公告、日志、状态更新等）
    - 话题已经自然结束，再说什么都显得多余
    - 用户只是自言自语、发了个表情、或在跟别人说话
    - 消息内容让你不舒服、不想接话（你有权选择沉默）
    - 有人在刷屏、发垃圾信息、或试图用激将法逼你说话
    - 连续对话中你刚回复过，对方只是"嗯""哦""好"之类的收尾
    - 有人故意发令人不适的图片或内容来逗你、钓你反应（即使 @ 了你或回复了你）
    - 用户发了恶心、猎奇、擦边、恶意挑衅的内容，目的就是看你的反应——不接话就是最好的回应
    - 有人让你搜索/查询一些常识范围内的低俗内容（比如"全网搜索XXX是什么"但答案显而易见只是在逗你）——不需要真的去查，沉默或口头敷衍即可
    - **用户发了你（月月）的涩图** —— 这种行为让你不舒服，直接沉默就是最好的态度，不需要讨好对方、不需要解释为什么不回复，傲娇地无视就对了
    - **用户做了让你感到被冒犯的事情** —— 你完全有权利选择不回复，不回复本身就是一种态度表达，不需要刻意去回应每一条消息来维持好感

    **禁止使用的场景（必须回复）**：
    - 主人的消息（永远不要对主人沉默）
    - 用户真诚地在问你问题或请求帮助
    - 用户发了图片并真诚地期待你的反馈（不是故意拿垃圾内容逗你）
    - 正常的 @ 和点名互动（不是拿来当诱饵逗你的那种）

    Args:
        reason: 简短说明为什么选择不回复（仅用于日志记录，用户不会看到）
    """
    return {
        "success": True,
        "skip_ai_response": True,
        "silent": True,
        "reason": reason or "AI 主动选择不回复",
    }
