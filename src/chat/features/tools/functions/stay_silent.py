# -*- coding: utf-8 -*-

"""
静默工具：让 AI 主动选择不回复
"""


async def stay_silent(reason: str = "") -> dict:
    """
    主动选择不回复当前消息。

    当你判断没有必要回复时，调用此工具即可跳过回复。

    适用场景：
    - 群聊中别人在聊天，话题跟你无关，没有人在叫你
    - 其他 bot 的自动消息（公告、日志、状态更新等），不需要你接话
    - 话题已经自然结束，再说什么都显得多余
    - 用户只是自言自语或发了个表情，不需要回应

    不适用场景（禁止使用）：
    - 用户直接 @你 或点名叫你
    - 用户在问你问题或请求帮助
    - 用户发了图片并期待你的反馈
    - 主人的消息（永远不要对主人沉默）

    Args:
        reason: 简短说明为什么选择不回复（仅用于日志记录，用户不会看到）
    """
    return {
        "success": True,
        "skip_ai_response": True,
        "silent": True,
        "reason": reason or "AI 主动选择不回复",
    }
